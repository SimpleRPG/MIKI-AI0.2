/**
 * P2006: 会話入力の下書き保持（依存ゼロの葉）。
 *
 * 会話画面（ChatPanel）はモバイル表示ではタブ切り替えで
 * アンマウントされ、コンポーネント内の useState だけでは
 * 打ちかけの下書きが消えた（実機 2026-11-23：入力中に文字が
 * 出ない／打った文字が消える、の一因）。下書きの正本を
 * モジュールレベルに置き、ChatPanel は初期値をここから取り、
 * 変更をここへ写す。再マウントでは正本から復元される。
 * クリアは送信成功時に ChatPanel が入力を空にすることでのみ
 * 起きる（写しが追随する）。永続化はしない：アプリ再起動を
 * 跨いで下書きを残す必要はなく、キー入力ごとの保存のような
 * 重い処理も入れない（メモリ上の保持のみ）。
 */
let draftText = '';

export const chatDraftStore = {
  /** 現在の下書き（再マウント時の初期値）。 */
  getDraft(): string {
    return draftText;
  },

  /** 下書きを写す（入力変更のたびに呼ばれる軽い代入のみ）。 */
  setDraft(text: string): void {
    draftText = text;
  },

  /** 下書きを空にする。 */
  clearDraft(): void {
    draftText = '';
  },
};
